const fs = require('fs');
const fsp = require('fs').promises;
const path = require('path');
const { chromium } = require('playwright');

class GeminiProfileManager {
  constructor() {
    this.baseDir = path.join(__dirname, '..', 'data', 'gemini_profiles');
    this.stateFilePath = path.join(this.baseDir, 'profiles_state.json');
    this.profiles = {
      profile_1: {
        id: 'profile_1',
        name: 'Gemini Account 1 (Primary)',
        dir: path.join(this.baseDir, 'profile_1'),
        dailyLimit: 3,
        videosGeneratedToday: 0,
        lastResetDate: null,
        lastActive: null,
        isLoggedIn: false,
        cooldownUntil: null
      },
      profile_2: {
        id: 'profile_2',
        name: 'Gemini Account 2 (Secondary)',
        dir: path.join(this.baseDir, 'profile_2'),
        dailyLimit: 3,
        videosGeneratedToday: 0,
        lastResetDate: null,
        lastActive: null,
        isLoggedIn: false,
        cooldownUntil: null
      }
    };
    this.ensureDirs();
    this.loadState();
  }

  ensureDirs() {
    if (!fs.existsSync(this.baseDir)) {
      fs.mkdirSync(this.baseDir, { recursive: true });
    }
    for (const key of ['profile_1', 'profile_2']) {
      if (!fs.existsSync(this.profiles[key].dir)) {
        fs.mkdirSync(this.profiles[key].dir, { recursive: true });
      }
    }
  }

  getTodayString() {
    return new Date().toISOString().split('T')[0];
  }

  loadState() {
    try {
      if (fs.existsSync(this.stateFilePath)) {
        const raw = fs.readFileSync(this.stateFilePath, 'utf8');
        const saved = JSON.parse(raw);
        const today = this.getTodayString();

        for (const id of ['profile_1', 'profile_2']) {
          if (saved[id]) {
            this.profiles[id] = { ...this.profiles[id], ...saved[id] };
            // Reset daily counters if day has rolled over
            if (this.profiles[id].lastResetDate !== today) {
              this.profiles[id].videosGeneratedToday = 0;
              this.profiles[id].lastResetDate = today;
              this.profiles[id].cooldownUntil = null;
            }
          }
        }
      }
    } catch (e) {
      console.warn('⚠️ Could not load profiles_state.json, initializing fresh state:', e.message);
    }
  }

  saveState() {
    try {
      this.ensureDirs();
      fs.writeFileSync(this.stateFilePath, JSON.stringify(this.profiles, null, 2), 'utf8');
    } catch (e) {
      console.error('❌ Failed to save profiles_state.json:', e.message);
    }
  }

  getProfileDir(profileId) {
    if (this.profiles[profileId]) {
      return this.profiles[profileId].dir;
    }
    throw new Error(`Unknown profile ID: ${profileId}`);
  }

  /**
   * Find which profile is available to generate videos right now.
   * Prioritizes profile_1 up to 3 videos, then automatically switches to profile_2.
   */
  getAvailableProfile() {
    this.loadState();
    const now = Date.now();

    for (const id of ['profile_1', 'profile_2']) {
      const p = this.profiles[id];
      // Check cooldown
      if (p.cooldownUntil && now < p.cooldownUntil) {
        continue;
      }
      // Check daily limit
      if (p.videosGeneratedToday < p.dailyLimit) {
        return p;
      }
    }

    return null; // Both profiles exhausted for today
  }

  /**
   * Record that a video was successfully generated by a profile
   */
  recordGeneration(profileId) {
    this.loadState();
    if (this.profiles[profileId]) {
      this.profiles[profileId].videosGeneratedToday += 1;
      this.profiles[profileId].lastActive = new Date().toISOString();
      this.profiles[profileId].lastResetDate = this.getTodayString();
      this.saveState();
    }
  }

  /**
   * Mark a profile as hitting quota limit / cooldown
   */
  markQuotaExhausted(profileId, cooldownHours = 24) {
    this.loadState();
    if (this.profiles[profileId]) {
      this.profiles[profileId].videosGeneratedToday = this.profiles[profileId].dailyLimit;
      this.profiles[profileId].cooldownUntil = Date.now() + (cooldownHours * 60 * 60 * 1000);
      this.saveState();
    }
  }

  /**
   * Mark profile login status
   */
  setLoginStatus(profileId, isLoggedIn, email = null) {
    this.loadState();
    if (this.profiles[profileId]) {
      this.profiles[profileId].isLoggedIn = Boolean(isLoggedIn);
      if (email) this.profiles[profileId].email = email;
      this.saveState();
    }
  }

  /**
   * Headless health check: Verifies if a profile is currently logged in to Gemini
   */
  async checkProfileHealth(profileId) {
    const profile = this.profiles[profileId];
    if (!profile) throw new Error(`Unknown profile: ${profileId}`);

    console.log(`🔍 Checking session for [${profile.name}]...`);
    const tempDir = path.join(__dirname, '..', 'temp');
    await fsp.mkdir(tempDir, { recursive: true });

    let context = null;
    try {
      context = await chromium.launchPersistentContext(profile.dir, {
        headless: true,
        viewport: { width: 1280, height: 800 },
        executablePath: '/usr/bin/google-chrome',
        args: [
          '--no-sandbox',
          '--disable-setuid-sandbox',
          '--disable-blink-features=AutomationControlled'
        ],
        ignoreDefaultArgs: ['--enable-automation']
      });

      const page = context.pages()[0] || await context.newPage();
      await page.goto('https://gemini.google.com/app', { waitUntil: 'domcontentloaded', timeout: 30000 });
      await page.waitForTimeout(4000);

      // Handle any welcome/personal intelligence modal popups if present
      try {
        const closeBtn = await page.$('button[aria-label*="Close"], button:has-text("Continue"), button:has-text("Dismiss"), button:has-text("Got it")');
        if (closeBtn) {
          console.log('   Dismissing popup modal...');
          await closeBtn.click();
          await page.waitForTimeout(1500);
        }
      } catch (_e) {}

      const hasSignIn = await page.$('button:has-text("Sign in"), a:has-text("Sign in")');
      const hasInput = await page.$('rich-textarea, [contenteditable="true"], .input-area, textarea');
      const hasNewChat = await page.$('button:has-text("New chat"), a:has-text("New chat"), [aria-label*="New chat"]');
      const isProUser = await page.$('text="Pro", div:has-text("susalabs"), [data-test-id*="user"]');

      const screenshotFile = path.join(tempDir, `${profileId}_status.png`);
      await page.screenshot({ path: screenshotFile });

      const isLoggedIn = !hasSignIn && (Boolean(hasInput) || Boolean(hasNewChat) || Boolean(isProUser));
      this.setLoginStatus(profileId, isLoggedIn, profileId === 'profile_1' ? 'susalabs44@gmail.com' : null);

      console.log(`   Result for ${profile.name}: ${isLoggedIn ? '✅ LOGGED IN' : '❌ NOT LOGGED IN'}`);
      console.log(`   Screenshot: ${screenshotFile}`);
      return { isLoggedIn, screenshotFile };
    } catch (err) {
      console.error(`   Error checking ${profileId}:`, err.message);
      return { isLoggedIn: false, error: err.message };
    } finally {
      if (context) await context.close();
    }
  }

  getStatusSummary() {
    this.loadState();
    return {
      profile_1: {
        name: this.profiles.profile_1.name,
        isLoggedIn: this.profiles.profile_1.isLoggedIn,
        email: this.profiles.profile_1.email || 'Not configured',
        videosToday: `${this.profiles.profile_1.videosGeneratedToday}/${this.profiles.profile_1.dailyLimit}`,
        remaining: Math.max(0, this.profiles.profile_1.dailyLimit - this.profiles.profile_1.videosGeneratedToday),
        cooldownUntil: this.profiles.profile_1.cooldownUntil ? new Date(this.profiles.profile_1.cooldownUntil).toLocaleString() : 'None'
      },
      profile_2: {
        name: this.profiles.profile_2.name,
        isLoggedIn: this.profiles.profile_2.isLoggedIn,
        email: this.profiles.profile_2.email || 'Not configured',
        videosToday: `${this.profiles.profile_2.videosGeneratedToday}/${this.profiles.profile_2.dailyLimit}`,
        remaining: Math.max(0, this.profiles.profile_2.dailyLimit - this.profiles.profile_2.videosGeneratedToday),
        cooldownUntil: this.profiles.profile_2.cooldownUntil ? new Date(this.profiles.profile_2.cooldownUntil).toLocaleString() : 'None'
      },
      totalAvailableToday: Math.max(0, this.profiles.profile_1.dailyLimit - this.profiles.profile_1.videosGeneratedToday) +
                           Math.max(0, this.profiles.profile_2.dailyLimit - this.profiles.profile_2.videosGeneratedToday)
    };
  }
}

module.exports = { GeminiProfileManager };
